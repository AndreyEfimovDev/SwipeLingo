import Foundation

// MARK: - SyncCursor
//
// Метка дельта-синка контента из Firestore (`updatedAt > метка`, ImportFSService). Книги синкаются
// полностью и метки не используют (см. BookFBService).
//
// Метка — самый поздний `updatedAt` среди полученных документов, а не `Date.now` устройства: `updatedAt`
// ставит Admin по своим часам, и сравнивать его надо с тем же источником. С временем устройства терялись
// документы, если часы телефона спешили или документ опубликовали, пока шёл синк.

enum SyncCursor {

    /// Новая метка после успешно сохранённого синка.
    /// - Parameters:
    ///   - previous: прежняя метка (`nil` — синка ещё не было).
    ///   - fetched: `updatedAt` полученных документов; `nil` — у документа поля нет, он не учитывается.
    /// - Returns: самый поздний `updatedAt` из полученных; если учитывать нечего — прежняя метка.
    ///   Может оказаться раньше прежней (полный синк после метки, поставленной по спешащим часам
    ///   устройства) — это безопасно: лишние документы просто придут ещё раз, upsert идемпотентен.
    static func next(previous: Date?, fetched: [Date?]) -> Date? {
        fetched.compactMap { $0 }.max() ?? previous
    }
}
